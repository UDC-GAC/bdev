export HADOOP_CONF_DIR_SRC="$SOLUTION_CONF_DIR_SRC"
export HADOOP_CONF_DIR="$SOLUTION_CONF_DIR"
export HADOOP_LOG_DIR="$SOLUTION_LOG_DIR"
export HADOOP_TEMPLATE_DIR="$SOLUTION_TEMPLATE_DIR"
