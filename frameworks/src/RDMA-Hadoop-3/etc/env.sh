export SOLUTION_TEMPLATE_DIR=$TEMPLATES_DIR/RDMA-Hadoop-3
export SOLUTION_BENCH_DIR="$BENCHMARKS_DIR/Hadoop"
export WORKERSFILE="$SOLUTION_CONF_DIR/workers"

#HADOOP environment variables
